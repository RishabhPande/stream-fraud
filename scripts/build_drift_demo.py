"""Build the interactive "Catch the drift" demo page.

Runs stream_fraud.replay for seeds 1-20 (with drift injected at txn 1200 and
matching no-drift runs) and embeds the real series into a self-contained
docs/drift-demo/index.html. Pure stdlib; no JavaScript build step.

    PYTHONPATH=. python scripts/build_drift_demo.py [out.html]

The page is static: open it directly or serve docs/drift-demo/ on any static
host. All data is synthetic, generated by stream_fraud.stream.
"""
import json
import sys
from pathlib import Path

from stream_fraud.ks import KSMonitor
from stream_fraud.replay import replay

SEEDS = range(1, 21)
N = 3000
DRIFT_AT = 1200
WINDOW = 400
ROLL = 100


def rolling_mean(xs, w):
    out, acc = [], 0.0
    for i, x in enumerate(xs):
        acc += x
        if i >= w:
            acc -= xs[i - w]
        out.append(acc / min(i + 1, w))
    return out


def seed_payload(seed):
    d = replay(n=N, drift_at=DRIFT_AT, seed=seed, window=WINDOW)
    q = replay(n=N, drift_at=None, seed=seed, window=WINDOW)
    row = {"seed": seed}
    for name, run in (("psi", d), ("ks", d)):
        at = getattr(run, f"{name}_alarm_at")
        row[name] = {
            "alarm_at": at,
            "delay": None if at is None or at < DRIFT_AT else at - DRIFT_AT,
            "early": at is not None and at < DRIFT_AT,
            "never": at is None,
            "false_alarm_no_drift": getattr(q, f"{name}_alarm_at") is not None,
        }
    return {
        "seed": seed,
        "score_roll": [round(x, 4) for x in rolling_mean(d.scores, ROLL)],
        "psi": [round(x, 4) for x in d.psi],
        "ks": [round(x, 4) for x in d.ks],
        "summary": row,
    }


def build(out_path, seeds=SEEDS):
    seeds = [seed_payload(s) for s in seeds]
    data = {
        "n": N,
        "drift_at": DRIFT_AT,
        "window": WINDOW,
        "roll": ROLL,
        "psi_threshold": 0.25,
        "ks_crit": round(KSMonitor(WINDOW, WINDOW)._crit(WINDOW, WINDOW), 4),
        "seeds": seeds,
    }
    template = Path(__file__).resolve().parents[1] / "docs" / "drift-demo" / "template.html"
    html = template.read_text()
    html = html.replace("__DRIFT_DATA__", json.dumps(data, separators=(",", ":")))
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(html)
    print("wrote", out_path, f"({len(html) // 1024} KB, {len(seeds)} seeds)")


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else str(
        Path(__file__).resolve().parents[1] / "docs" / "drift-demo" / "index.html")
    build(out)
